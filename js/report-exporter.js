/**
 * RESUMETRACKER: MARKDOWN AUDIT REPORT EXPORTER
 * Generates formatted Markdown summaries of Google, Amazon, and ATS audits
 * ready for Notion, Obsidian, GitHub, or mentor coaching sessions.
 */

/**
 * Triggers a client-side file download of raw Markdown content
 */
export function downloadMarkdownFile(filename, markdownContent) {
  const blob = new Blob([markdownContent], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Formats a comprehensive Google ATS & Profile Audit into Markdown
 */
export function generateGoogleAuditMarkdown(audit, candidateName = "Candidate", targetRole = "Google Software Engineer") {
  const dateStr = new Date().toISOString().split("T")[0];
  const { googleAtsScore, tier, dimensions, levelEval } = audit;

  return `# Google Technical Resume & ATS Audit Report

**Candidate:** ${candidateName}  
**Target Role / Scope:** ${targetRole}  
**Date:** ${dateStr}  
**Overall Google ATS Score:** **${googleAtsScore}%** (${tier})  
**Assessed Scope Level:** **${levelEval.level} (${levelEval.title})**  

---

## 📊 Evaluation Pillars (Google 4-Pillar Rubric)

| Dimension | Score | Description & Benchmark |
| :--- | :--- | :--- |
| **XYZ Formula Density** | **${dimensions.xyzDensity}%** | Adherence to *"Accomplished [X] as measured by [Y], by doing [Z]"* |
| **Role-Related Knowledge (RRK)** | **${dimensions.rrk}%** | Canonical algorithms, systems design, concurrency, and architecture |
| **General Cognitive Ability (GCA)** | **${dimensions.gca}%** | Root-cause diagnostic problem solving and ambiguous challenge resolution |
| **Leadership & Ownership** | **${dimensions.leadership}%** | Cross-functional alignment, mentorship, technical initiative, and RFCs |

---

## 🎯 Leveling Diagnostic & Roadmap (${levelEval.level})

**Summary:**  
${levelEval.summary}

### Key Actionable Recommendations to Hit Bar:
${levelEval.recommendations.map(r => `- ${r}`).join("\n")}

---

*Generated by [ResumeATS](https://github.com/deadheaven07/ResumeATS) • 100% Client-Side Private*
`;
}

/**
 * Formats a comprehensive Amazon Bar Raiser & 16 LPs Audit into Markdown
 */
export function generateAmazonAuditMarkdown(audit, candidateName = "Candidate", targetRole = "Amazon Software Development Engineer") {
  const dateStr = new Date().toISOString().split("T")[0];
  const { amazonScore, tier, dimensions, lpCoverageCount, lpResults } = audit;

  let lpTable = "| Leadership Principle | Status | Matched Evidence Tokens |\n| :--- | :--- | :--- |\n";
  lpResults.forEach(lp => {
    const status = lp.covered ? "✅ Covered" : "❌ Missing";
    const tokens = lp.matchedTokens.length > 0 ? lp.matchedTokens.join(", ") : "*None detected*";
    lpTable += `| **${lp.name}** | ${status} | ${tokens} |\n`;
  });

  return `# Amazon Bar Raiser & 16 Leadership Principles Audit Report

**Candidate:** ${candidateName}  
**Target Role / Track:** ${targetRole}  
**Date:** ${dateStr}  
**Overall Amazon Bar Score:** **${amazonScore}%** (${tier})  
**16 LP Coverage:** **${lpCoverageCount} / 16 Principles Verified**  

---

## 📊 Bar Raiser Evaluation Dimensions

| Dimension | Score | Focus Area |
| :--- | :--- | :--- |
| **16 LP Coverage** | **${dimensions.lpCoverage}%** | Breadth and frequency of Leadership Principle signals across experience |
| **AWS & Distributed Scale** | **${dimensions.scale}%** | High-throughput, cloud architecture, and resiliency metrics |
| **Operational Excellence** | **${dimensions.operationalExcellence}%** | On-call ownership, postmortems, SLAs, automated alerting, and 5-Whys |
| **Customer Obsession** | **${dimensions.customerObsession}%** | Working backwards from customer pain to deliver measurable business impact |

---

## 🏛️ 16 Leadership Principles Evidence Breakdown

${lpTable}

---

*Generated by [ResumeATS](https://github.com/deadheaven07/ResumeATS) • 100% Client-Side Private*
`;
}
